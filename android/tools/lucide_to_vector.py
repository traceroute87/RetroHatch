#!/usr/bin/env python3
"""Fetch Lucide icons (ISC licence, see android/LUCIDE_LICENSE.txt) from a PINNED lucide-static release and write them as Android VectorDrawables
(app/src/main/res/drawable/ic_<name>.xml, `-` -> `_`). Stroke-only, 24x24 viewport, stroke 2, round caps/joins, white: the UI tints them at run time.
Run once after changing ICONS; the generated XML is committed, so the build never needs the network.
    python android/tools/lucide_to_vector.py"""
import re, sys, urllib.request, xml.etree.ElementTree as ET
from pathlib import Path

VERSION = "0.468.0"
ICONS = ["compass", "layout-grid", "refresh-cw", "settings", "download", "package-plus", "trash-2", "external-link", "search", "arrow-left", "chevron-right",
         "wifi", "wifi-off", "triangle-alert", "circle-check", "circle-x", "circle-arrow-up", "info", "shield-check", "lock", "database", "smartphone", "globe",
         "code", "scale", "hard-drive", "tag", "user", "package", "package-open", "loader-circle", "list", "cpu", "circle-check-big", "x", "play"]
OUT = Path(__file__).resolve().parents[1] / "app" / "src" / "main" / "res" / "drawable"
NS = "{http://www.w3.org/2000/svg}"


def n(v):
    return f"{float(v):g}"


def shape(e):
    t = e.tag.removeprefix(NS); a = e.attrib; f = lambda k, d=0: float(a.get(k, d))
    if t == "path":
        return a["d"]
    if t == "line":
        return f"M{n(f('x1'))} {n(f('y1'))}L{n(f('x2'))} {n(f('y2'))}"
    if t in ("polyline", "polygon"):
        p = re.findall(r"-?\d*\.?\d+", a["points"])
        return "M" + " ".join(p[:2]) + "L" + " ".join(p[2:]) + ("Z" if t == "polygon" else "")
    if t == "circle":
        cx, cy, r = f("cx"), f("cy"), f("r")
        return f"M{n(cx - r)} {n(cy)}a{n(r)} {n(r)} 0 1 0 {n(2 * r)} 0a{n(r)} {n(r)} 0 1 0 {n(-2 * r)} 0Z"
    if t == "ellipse":
        cx, cy, rx, ry = f("cx"), f("cy"), f("rx"), f("ry")
        return f"M{n(cx - rx)} {n(cy)}a{n(rx)} {n(ry)} 0 1 0 {n(2 * rx)} 0a{n(rx)} {n(ry)} 0 1 0 {n(-2 * rx)} 0Z"
    if t == "rect":
        x, y, w, h = f("x"), f("y"), f("width"), f("height")
        rx = f("rx", a.get("ry", 0)); ry = f("ry", rx)
        if not rx:
            return f"M{n(x)} {n(y)}H{n(x + w)}V{n(y + h)}H{n(x)}Z"
        return (f"M{n(x + rx)} {n(y)}H{n(x + w - rx)}A{n(rx)} {n(ry)} 0 0 1 {n(x + w)} {n(y + ry)}V{n(y + h - ry)}A{n(rx)} {n(ry)} 0 0 1 {n(x + w - rx)} {n(y + h)}"
                f"H{n(x + rx)}A{n(rx)} {n(ry)} 0 0 1 {n(x)} {n(y + h - ry)}V{n(y + ry)}A{n(rx)} {n(ry)} 0 0 1 {n(x + rx)} {n(y)}Z")
    raise SystemExit(f"unsupported svg element {t}")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name in ICONS:
        svg = urllib.request.urlopen(f"https://unpkg.com/lucide-static@{VERSION}/icons/{name}.svg", timeout=30).read().decode()
        root = ET.fromstring(re.sub(r"<!--.*?-->", "", svg, flags=re.S))
        paths = [shape(e) for e in root if isinstance(e.tag, str)]
        body = "\n".join(f'    <path android:pathData="{d}"\n        android:strokeColor="#FFFFFFFF" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" />' for d in paths)
        xml = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Lucide "%s" v%s, ISC licence (android/LUCIDE_LICENSE.txt). Generated by tools/lucide_to_vector.py. -->\n'
               '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n%s\n</vector>\n') % (name, VERSION, body)
        (OUT / f"ic_{name.replace('-', '_')}.xml").write_text(xml, encoding="utf-8")
        print("ok", name, len(paths))


if __name__ == "__main__":
    main()
