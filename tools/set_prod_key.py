#!/usr/bin/env python3
"""Install the PRODUCTION public key (64 hex chars, from your offline `trust.py keygen`) into the repo.

  python tools/set_prod_key.py <public key hex>

Writes catalog/production.pub (read by tools/trust.py and the Pages workflow) and
platforms/nano/ui/trusted_keys_prod.h (compiled into the production OPK). Public data only; the private key never
comes near this repository."""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if len(sys.argv) != 2 or not re.fullmatch(r"[0-9a-f]{64}", sys.argv[1]):
    sys.exit("usage: set_prod_key.py <64 lowercase hex chars>  (the public key printed by trust.py keygen)")
h = sys.argv[1]
(ROOT / "catalog" / "production.pub").write_bytes((h + "\n").encode())
b = ",".join("0x" + h[i:i + 2] for i in range(0, 64, 2))
(ROOT / "platforms" / "nano" / "ui" / "trusted_keys_prod.h").write_bytes(f"""/* Production builds: the production catalog signing key's PUBLIC half (generated by tools/set_prod_key.py from
 * catalog/production.pub). The private half exists only offline. */
#ifndef RH_TRUSTED_KEYS_H
#define RH_TRUSTED_KEYS_H
#include <stdint.h>
static const uint8_t RH_TRUSTED_KEYS[][32] = {{{{{b}}}}};
#define RH_N_TRUSTED_KEYS 1
#endif
""".encode())
print("production key installed:", h[:16] + "...")
